create table if not exists public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  description text not null default '',
  price numeric(10, 2) not null check (price > 0),
  available boolean not null default true,
  image_url text,
  created_at timestamptz not null default now()
);

create table if not exists public.home_images (
  id bigint generated by default as identity primary key,
  title text not null,
  image_url text not null,
  position integer not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.admin_users (
  user_id uuid primary key references auth.users (id) on delete cascade,
  created_at timestamptz not null default now()
);

alter table public.products enable row level security;
alter table public.home_images enable row level security;
alter table public.admin_users enable row level security;

drop policy if exists "products_public_read" on public.products;
create policy "products_public_read"
  on public.products for select to anon, authenticated
  using (true);

drop policy if exists "products_admin_manage" on public.products;
create policy "products_admin_manage"
  on public.products for all to authenticated
  using (exists (select 1 from public.admin_users where user_id = auth.uid()))
  with check (exists (select 1 from public.admin_users where user_id = auth.uid()));

drop policy if exists "home_images_public_read" on public.home_images;
create policy "home_images_public_read"
  on public.home_images for select to anon, authenticated
  using (true);

drop policy if exists "home_images_admin_manage" on public.home_images;
create policy "home_images_admin_manage"
  on public.home_images for all to authenticated
  using (exists (select 1 from public.admin_users where user_id = auth.uid()))
  with check (exists (select 1 from public.admin_users where user_id = auth.uid()));

drop policy if exists "admin_users_read_self" on public.admin_users;
create policy "admin_users_read_self"
  on public.admin_users for select to authenticated
  using (user_id = auth.uid());

grant usage on schema public to anon, authenticated;
grant select on public.products, public.home_images to anon, authenticated;
grant insert, update, delete on public.products, public.home_images to authenticated;
grant select on public.admin_users to authenticated;
grant usage, select on sequence public.products_id_seq, public.home_images_id_seq to authenticated;

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'site-images',
  'site-images',
  true,
  5242880,
  array['image/jpeg', 'image/png', 'image/webp']
)
on conflict (id) do update set
  public = excluded.public,
  file_size_limit = excluded.file_size_limit,
  allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists "site_images_public_read" on storage.objects;
create policy "site_images_public_read"
  on storage.objects for select to anon, authenticated
  using (bucket_id = 'site-images');

drop policy if exists "site_images_admin_upload" on storage.objects;
create policy "site_images_admin_upload"
  on storage.objects for insert to authenticated
  with check (
    bucket_id = 'site-images'
    and exists (select 1 from public.admin_users where user_id = auth.uid())
  );

drop policy if exists "site_images_admin_update" on storage.objects;
create policy "site_images_admin_update"
  on storage.objects for update to authenticated
  using (
    bucket_id = 'site-images'
    and exists (select 1 from public.admin_users where user_id = auth.uid())
  )
  with check (
    bucket_id = 'site-images'
    and exists (select 1 from public.admin_users where user_id = auth.uid())
  );

drop policy if exists "site_images_admin_delete" on storage.objects;
create policy "site_images_admin_delete"
  on storage.objects for delete to authenticated
  using (
    bucket_id = 'site-images'
    and exists (select 1 from public.admin_users where user_id = auth.uid())
  );
